"""
Test Pattern Store - Testing conventions and requirements
"""

from typing import Any, Dict, List, Optional
from .base import BaseStore


class TestPatternStore(BaseStore):
    """
    Manages test pattern memory.

    Tracks:
    - Testing conventions
    - Required test cases by pattern
    - Coverage gaps
    - Test-bug relationships
    """

    def add_convention(
        self,
        category: str,
        pattern: str,
        required_for: str = "all"
    ) -> str:
        """Add a testing convention"""
        conv_id = self._make_id("tc", f"{category}_{pattern[:20]}")

        self.graph.add_node(
            "test_convention",
            conv_id,
            category=category,
            pattern=self._sanitize(pattern),
            required_for=required_for,
        )

        return conv_id

    def add_required_cases(
        self,
        for_pattern: str,
        cases: List[str],
        rationale: Optional[str] = None
    ) -> str:
        """Add required test cases for a pattern"""
        req_id = self._make_id("rtc", for_pattern[:20])

        self.graph.add_node(
            "required_test_case",
            req_id,
            for_pattern=for_pattern,
            cases_required=",".join(cases),
            rationale=self._sanitize(rationale or ""),
        )

        return req_id

    def add_coverage_gap(
        self,
        module_path: str,
        current: float,
        target: float,
        gap_areas: List[str]
    ) -> str:
        """Record a coverage gap"""
        gap_id = self._make_id("cg", module_path)

        self.graph.add_node(
            "coverage_gap",
            gap_id,
            module=module_path,
            current_coverage=str(current),
            target_coverage=str(target),
            gap_areas=",".join(gap_areas),
        )

        return gap_id

    def link_test_to_bug(
        self,
        bug_title: str,
        test_name: str
    ) -> None:
        """Link a regression test to a bug"""
        bug_id = self._make_id("bug", bug_title[:30])

        self.graph.add_edge(
            "TEST_FOR_BUG",
            ("test", test_name),
            ("bug", bug_id),
            added=self._now()
        )

    def record_generated_tests(
        self,
        for_function: str,
        coverage_added: float,
        cases_covered: List[str],
        missing: Optional[List[str]] = None
    ) -> None:
        """Record tests generated by agent"""
        self.graph.add_edge(
            "AGENT_GENERATED_TESTS",
            ("agent", "self"),
            ("function", for_function),
            coverage_added=str(coverage_added),
            edge_cases_covered=",".join(cases_covered),
            missing=",".join(missing or []),
            when=self._now()
        )

    def get_test_requirements(self, pattern: str) -> Dict[str, Any]:
        """Get testing requirements for a pattern"""
        requirements = {
            "conventions": [],
            "required_cases": [],
        }

        for node in self.graph.nodes():
            if node.type == "test_convention":
                req_for = node.properties.get("required_for", "all")
                if req_for == "all" or pattern in req_for:
                    requirements["conventions"].append(node.properties)

            elif node.type == "required_test_case":
                if pattern in node.properties.get("for_pattern", ""):
                    cases = node.properties.get("cases_required", "").split(",")
                    requirements["required_cases"].extend(cases)

        return requirements

    def get_coverage_gaps(self) -> List[Dict[str, Any]]:
        """Get all coverage gaps"""
        return [
            {"id": node.id, **node.properties}
            for node in self.graph.nodes()
            if node.type == "coverage_gap"
        ]

    def get_relevant(self, context: Dict[str, Any]) -> List[Dict[str, Any]]:
        """Get relevant test patterns for context"""
        results = []

        # Get test requirements based on task type
        task = context.get("task", "")
        task_lower = task.lower()

        patterns = ["any_function"]
        if "graph" in task_lower:
            patterns.append("graph_operation")
        if "async" in task_lower:
            patterns.append("async_function")
        if "file" in task_lower:
            patterns.append("file_operation")

        for pattern in patterns:
            reqs = self.get_test_requirements(pattern)
            if reqs["conventions"] or reqs["required_cases"]:
                results.append({
                    "type": "test_requirements",
                    "pattern": pattern,
                    **reqs
                })

        return results

    def get_stats(self) -> Dict[str, int]:
        """Get test pattern store statistics"""
        conventions = 0
        required_cases = 0
        gaps = 0
        generated = 0

        for node in self.graph.nodes():
            if node.type == "test_convention":
                conventions += 1
            elif node.type == "required_test_case":
                required_cases += 1
            elif node.type == "coverage_gap":
                gaps += 1

        for edge in self.graph.edges():
            if edge.rel_type == "AGENT_GENERATED_TESTS":
                generated += 1

        return {
            "conventions": conventions,
            "required_case_sets": required_cases,
            "coverage_gaps": gaps,
            "agent_generated": generated,
        }
